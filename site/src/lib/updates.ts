export interface DayLog {
  date: string;
  notes: string[];
  items: string[]; // slug
  guides: string[];
}

/** 정정 기록과 페이지 추가를 날짜별로 합쳐 최신순으로. */
export function dayLogs(): DayLog[] {
  const days = new Map<string, DayLog>();
  const day = (date: string) => {
    if (!days.has(date)) days.set(date, { date, notes: [], items: [], guides: [] });
    return days.get(date)!;
  };
  for (const n of NOTES) day(n.date).notes.push(...n.notes);
  for (const [key, date] of Object.entries(added as Record<string, string>)) {
    const [kind, slug] = key.split('/');
    (kind === 'guides' ? day(date).guides : day(date).items).push(slug);
  }
  return [...days.values()].sort((a, b) => b.date.localeCompare(a.date));
}
