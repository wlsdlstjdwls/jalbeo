MEASURE = ("신규후보", "별칭확인")


def main():
    rows = list(csv.DictReader(io.open(SRC, encoding="utf-8-sig")))

    missing = [r["item"] for r in rows if r["item"] not in TRIAGE]
    if missing:
        sys.exit("분류 안 된 후보 %d개: %s" % (len(missing), ", ".join(missing)))
    extra = [k for k in TRIAGE if k not in {r["item"] for r in rows}]
    if extra:
        sys.exit("후보에 없는 분류 %d개: %s" % (len(extra), ", ".join(extra)))

    out = []
    for r in rows:
        decision, why = TRIAGE[r["item"]]
        out.append({
            "item": r["item"],
            "decision": decision,
            "note": why,
            "freq": r["freq"],
            "n_queries": r["n_queries"],
            "sample_suggestion": r["sample_suggestion"],
        })
    # 실측 대상을 위로, 그 안에서는 등장 빈도순
    order = {"신규후보": 0, "별칭확인": 1, "별칭": 2, "가이드축": 3,
             "총칭": 4, "조합어": 5, "B층폐기": 6, "범위밖": 7}
    out.sort(key=lambda r: (order[r["decision"]], -int(r["freq"]), r["item"]))

    with io.open(OUT, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=[
            "item", "decision", "note", "freq", "n_queries", "sample_suggestion"])
        w.writeheader()
        w.writerows(out)

    counts = Counter(r["decision"] for r in out)
    print("후보 %d개 분류" % len(out))
    for k in order:
        if counts[k]:
            print("  %-8s %3d" % (k, counts[k]))
    measured = [r["item"] for r in out if r["decision"] in MEASURE]
    print("\n실측 대상 %d개: %s" % (len(measured), ", ".join(measured)))
    print("-> %s" % OUT)


if __name__ == "__main__":
    main()
