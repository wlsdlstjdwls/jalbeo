HEADER = """# 실측 16차 묶음 -- 품목사전 잔여 {n_topic}주제

씨앗은 분리의정석 품목사전(`data/keywords/candidates-bunri.csv`) 중
현재 어휘 1,197개와 실측 12~15차 378주제를 뺀 290개다. 여기서 판단 40번으로
{n_topic}개를 골랐다. 키워드 {n_kw}개, {n_batch}묶음.

**측정 결과가 0이어도 0으로 적지 않는다.** 조회에 안 걸린 것은 빈칸이다
(미측정은 null, CLAUDE.md 작업 규칙).

| 주제 | 축 | 등재 | 미룬 표기 | 무엇이 갈리나 |
|---|---|---|---|---|
{table}

## 묶는 법

키워드 도구는 씨앗을 한 번에 5개까지 받는다. 아래 묶음을 통째로 복사해
[네이버 검색광고 > 키워드도구]에 붙이고 조회한 뒤 다운로드한다.
받은 xlsx는 전부 `data/keywords/gate1-16/`에 넣는다.
"""


def keywords():
    out = []
    for name, axis, _, _, _ in TOPICS:
        for suf in SUFFIXES:
            out.append((name, "%s %s" % (name, suf)))
    return out


def main():
    pairs = keywords()
    batches = [pairs[i:i + PER_BATCH] for i in range(0, len(pairs), PER_BATCH)]
    table = "\n".join(
        "| %s | %s | %s | %s | %s |"
        % (name, axis, ("%d곳" % n) if n else "-", later or "-", why)
        for name, axis, n, later, why in TOPICS)

    out = [HEADER.format(n_topic=len(TOPICS), n_kw=len(pairs),
                         n_batch=len(batches), table=table), ""]
    for i, batch in enumerate(batches, 1):
        labels = []
        for topic, _ in batch:
            if topic not in labels:
                labels.append(topic)
        out.append("**%d/%d** - %s" % (i, len(batches), " + ".join(labels)))
        out.append("")
        out.append("```")
        out.extend(kw for _, kw in batch)
        out.append("```")
        out.append("")

    io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("%s -- 주제 %d개, 키워드 %d개, %d묶음"
          % (OUT, len(TOPICS), len(pairs), len(batches)))


if __name__ == "__main__":
    main()
