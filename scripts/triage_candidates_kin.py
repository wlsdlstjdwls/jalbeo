def hand(name):
    """손으로 적은 표. 기계보다 먼저다."""
    if name in BATCH20:
        return "실측20차", BATCH20[name]
    if name in COVERED:
        return "기존 커버", COVERED[name]
    if name in HOLD:
        return "보류", HOLD[name]
    return None, None


def mech(name):
    s = name.strip()
    flat = s.replace(" ", "")
    if not re.search(r"[가-힣]", s):
        return "노이즈", "한글이 없다"
    if len(flat) <= 1:
        return "노이즈", "한 글자 토막"
    if TAIL.search(s):
        return "노이즈", "꼬리말 잔재"
    if LIFE.search(s):
        return "노이즈", "물건이 아니라 사람의 사정"
    if SENTENCE.search(s):
        return "노이즈", "문장 토막"
    if ADDR.search(s):
        return "지역", "B층 폐기 (확정 판단 1)"
    if BIZ.search(s):
        return "사업장", "생활폐기물 축 밖"
    if ADNOM.match(flat):
        return "노이즈", "관형형만 남았다"
    if flat in GENERIC or s in GENERIC:
        return "노이즈", "총칭 또는 토막"
    return None, None


def main():
    dry = "--dry" in sys.argv
    rows = list(csv.DictReader(io.open(SRC, encoding="utf-8-sig")))
    fields = rows[0].keys()

    counts, changed, left = Counter(), 0, []
    for r in rows:
        if r["decision"].strip():
            continue
        name = r["item"].strip()
        dec, why = hand(name)
        if dec is None:
            dec, why = mech(name)
        if dec is None:
            dec, why = "노이즈", "표에도 규칙에도 안 걸린 토막"
            left.append(name)
        counts[dec] += 1
        changed += 1
        if dec == "실측20차":
            r["decision"] = "실측20차"
            r["note"] = why
        elif dec == "기존 커버":
            r["decision"] = "기존 커버"
            r["covered_by"] = r["covered_by"] or why
            r["note"] = r["note"] or why
        else:
            r["decision"] = dec
            r["note"] = r["note"] or why

    for dec, n in counts.most_common():
        print("%-8s %5d" % (dec, n))
    print("-" * 20)
    print("갈랐다 %d개, 표에도 규칙에도 안 걸린 것 %d개" % (changed, len(left)))
    if left:
        print("  " + ", ".join(left[:40]))

    if dry:
        print("(--dry, 안 썼다)")
        return
    with io.open(SRC, "w", encoding="utf-8", newline="") as fp:
        w = csv.DictWriter(fp, fieldnames=list(fields))
        w.writeheader()
        w.writerows(rows)
    print("%s 갱신" % SRC)


if __name__ == "__main__":
    main()
