NOISE_WHY = "표에도 규칙에도 안 걸린 토막"


def norm(s):
    return re.sub(r"\s+", "", s).lower()


def decide(name, mech):
    key = name.strip()
    if key in BATCH21:
        return "실측21차", BATCH21[key]
    if key in COVER:
        return "기존 커버", COVER[key]
    if key in HOLD:
        return "보류", HOLD[key]
    if key in BIZ_EXTRA:
        return "사업장", "의료, 실험실. 생활폐기물 축 밖이다"
    dec, why = mech(key)
    if dec:
        return dec, why
    return "노이즈", NOISE_WHY


def main():
    dry = "--dry" in sys.argv
    rows = list(csv.DictReader(io.open(SRC, encoding="utf-8-sig")))
    fields = list(rows[0].keys())

    counts, left, topics = Counter(), [], Counter()
    for r in rows:
        if r["decision"].strip():
            continue
        name = r["item"].strip()
        dec, why = decide(name, MECH)
        counts[dec] += 1
        if dec == "노이즈" and why == NOISE_WHY:
            left.append(name)
        if dec == "실측21차":
            topics[why] += 1
        r["decision"] = dec
        if dec == "기존 커버":
            r["covered_by"] = r["covered_by"] or why
        r["note"] = why if dec in ("실측21차", "기존 커버", "보류") else (r["note"] or why)

    for dec, n in counts.most_common():
        print("%-8s %5d" % (dec, n))
    print("-" * 26)
    print("실측 21차 주제 %d개(표기 %d건)" % (len(topics), sum(topics.values())))
    print("표에도 규칙에도 안 걸린 토막 %d개" % len(left))
    if left:
        print("  " + ", ".join(left[:30]))

    if dry:
        print("(--dry, 안 썼다)")
        return
    with io.open(SRC, "w", encoding="utf-8", newline="") as fp:
        w = csv.DictWriter(fp, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)
    print("%s 갱신" % SRC)


MECH = load_mech()

if __name__ == "__main__":
    main()
